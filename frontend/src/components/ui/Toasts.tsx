"use client";

import { useChat } from "@/store/chat";

export function Toasts() {
  const toasts = useChat((s) => s.toasts);
  return (
    <div className="toasts" aria-live="polite">
      {toasts.map((t) => (
        <div key={t.id} className="toast">
          {t.text}
        </div>
      ))}
    </div>
  );
}
